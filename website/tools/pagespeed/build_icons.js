#!/usr/bin/env node
/*
 * Build <theme>/assets/js/icons.js: the Lucide icons the AMATEC theme uses,
 * taken from one pinned Lucide release, plus Lucide's own createIcons()
 * logic, so the SVG markup matches what the full CDN bundle produced.
 *
 * Icon names are found by scanning every quoted kebab-case string in the
 * theme's PHP and JS and keeping the ones that are Lucide icons, which also
 * catches names held in PHP arrays and JS. A name added later without a
 * rebuild still renders: icons.js then loads the full pinned bundle.
 *
 * Usage:  node build_icons.js <theme-dir> [lucide-version]
 * Re-run after adding or renaming an icon anywhere in the theme.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const Module = require('module');

const theme = process.argv[2];
const version = process.argv[3] || '1.65.0';
if (!theme || !fs.existsSync(path.join(theme, 'functions.php'))) {
  console.error('Usage: node build_icons.js <theme-dir> [lucide-version]');
  process.exit(1);
}
const OUT = path.join(theme, 'assets', 'js', 'icons.js');

// Same name conversion as lucide's toPascalCase().
function toPascalCase(s) {
  let out = '';
  let upperNext = false;
  for (const ch of s) {
    if (ch === '-' || ch === '_' || ch <= ' ') { upperNext = out.length > 0; continue; }
    out += out.length === 0 ? ch.toLowerCase() : (upperNext ? ch.toUpperCase() : ch);
    upperNext = false;
  }
  return out.charAt(0).toUpperCase() + out.slice(1);
}

function themeFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return themeFiles(p);
    return /\.(php|js)$/.test(e.name) && p !== OUT ? [p] : [];
  });
}

(async () => {
  const url = `https://unpkg.com/lucide@${version}/dist/umd/lucide.js`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const m = new Module(url);
  m._compile(await res.text(), 'lucide.js');
  const lucide = m.exports;

  const names = new Set();
  for (const file of themeFiles(theme)) {
    const src = fs.readFileSync(file, 'utf8');
    for (const [, name] of src.matchAll(/['"]([a-z](?:[a-z0-9-]*[a-z0-9])?)['"]/g)) {
      if (Array.isArray(lucide[toPascalCase(name)])) names.add(name);
    }
  }
  const icons = {};
  for (const name of [...names].sort()) icons[toPascalCase(name)] = lucide[toPascalCase(name)];

  const runtime = fs.readFileSync(path.join(__dirname, 'icons-runtime.js'), 'utf8')
    .replace(/\/\*\*[\s\S]*?\*\/\n/, '') // drop the file's own doc comment
    .replace('__VERSION__', version)
    .replace('__ICONS__', JSON.stringify(icons));
  const header = `/*! Lucide icons v${version} subset for the AMATEC theme (${names.size} icons). ` +
    'ISC License, Copyright (c) Lucide Contributors. Generated by build_icons.js, do not edit. */\n';
  fs.writeFileSync(OUT, header + runtime);
  console.log(`${names.size} icons, ${fs.statSync(OUT).size} bytes -> ${OUT}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
